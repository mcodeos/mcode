#!/usr/bin/env python3
"""Alias-registry projection: answer sheets -> build/param-aliases.toml.

The law source is the `alias: [...]` face on answer-sheet column rows
(mcode comp books; mcd 3.design/library/305 section 3). This script only
projects it into a flat lookup table for scraping pipelines; the output is
regenerable and never hand-edited. Canonical keys stay the only key face;
aliases never enter spec keys (check-spec-keys enforces the consumer side).
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "build" / "param-aliases.toml"

ROW = re.compile(r'^\s{4,}(\w+)\s+=\s+(\w+),\s*alias:\s*\[([^\]]*)\]')
RECIPE = re.compile(r'^recipe\s+([\w.]+)')
GROUP = re.compile(r'^\s{4,}(\w+)\s+=\s*\[')


def main() -> int:
    rows = []
    for path in sorted((ROOT / "comp").glob("*.mc")):
        recipe = None
        group = None
        for line in path.read_text().splitlines():
            m = RECIPE.match(line)
            if m:
                recipe, group = m.group(1), None
                continue
            m = GROUP.match(line)
            if m:
                group = m.group(1)
                continue
            m = ROW.match(line)
            if m and recipe and group:
                col, typ, aliases = m.groups()
                names = [a.strip() for a in aliases.split(",") if a.strip()]
                if names:
                    rows.append((recipe, group, col, typ, names, path.name))

    lines = [
        "# Generated by scripts/alias-projection.py - regenerable, never hand-edited.",
        "# Law source: alias: [...] faces on comp/*.mc answer-sheet columns (305 s3).",
        "",
    ]
    for recipe, group, col, typ, names, src in rows:
        lines.append(f'["{recipe}.{col}"]')
        lines.append(f'group = "{group}"')
        lines.append(f'type = "{typ}"')
        lines.append("aliases = [" + ", ".join(f'"{n}"' for n in names) + "]")
        lines.append(f'source = "comp/{src}"')
        lines.append("")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"alias-projection: {len(rows)} columns -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
