"""Generate the engine-side domain declarations from the group tables.

The group tables under `tables/` are the truth: they say which enum member
belongs to which logical group, and which spec key each group may fill.
The engine cannot read a JSON table, so the table is projected into a
`.mc` declaration face: one domain declaration per (enum, spec key) pair.

The projection is generated, never hand-edited: a hand-edited copy is a
second truth that drifts.  The pre-commit hook regenerates and compares, so
a stale declaration fails the commit instead of quietly mis-judging a value.

Usage
    python3 scripts/gen-domains.py            -- write the declarations
    python3 scripts/gen-domains.py --check    -- fail when they are stale
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLES = ROOT / "tables"

HEADER = (
    "# Copyright (c) 2026 MCode. Built with MCode Bench(TM).\n"
    "# Licensed under the Apache License, Version 2.0.\n"
)


def load_tables():
    """The group tables of the library, sorted by file name."""
    out = []
    for path in sorted(TABLES.glob("*.groups.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        out.append((path, data))
    return out


def declarations(data):
    """The domain declarations of one group table.

    A table declares a group per spec key: the key may only take the words
    of its own group.  A table without a keyed face constrains no value, so
    it declares nothing.
    """
    enum = data["enum"]
    groups = data.get("groups") or {}
    keys = data.get("keys") or {}
    out = []
    for key, group in sorted(keys.items()):
        members = groups.get(group)
        if not members:
            continue
        out.append((enum, key, group, list(members)))
    return out


def render(enum, key, group, members):
    """One domain declaration block."""
    words = ", ".join(members)
    return (
        f"meta {enum}.{key} {{\n"
        f"    words = {enum}\n"
        f"    values = {words}\n"
        f"    key = {key}\n"
        f"}}\n"
    )


def build():
    """The generated text of every declaration file, keyed by file name."""
    files = {}
    aggregate = []
    for path, data in load_tables():
        decls = declarations(data)
        if not decls:
            continue
        stem = path.name[: -len(".groups.json")]
        body = "\n".join(render(*d) for d in decls)
        files[f"{stem}.domains.mc"] = body
        aggregate.append(f"pub use ./{stem}.domains.mc\n")
    files["domains.mc"] = "\n".join(aggregate)
    return files


def render_file(text):
    """The whole file: header, a generation note, then the declarations."""
    return HEADER + "\n// Generated by scripts/gen-domains.py from the group tables.\n" \
        + "// Edit the tables, not this file.\n\n" + text


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="fail when the generated declarations are stale")
    args = ap.parse_args()

    stale = []
    for name, text in sorted(build().items()):
        path = TABLES / name
        want = render_file(text)
        if not path.exists():
            stale.append(name)
            continue
        if path.read_text(encoding="utf-8") != want:
            stale.append(name)
    if stale:
        if args.check:
            for name in stale:
                print(f"gen-domains: stale declaration file: tables/{name}")
            print("gen-domains: run scripts/gen-domains.py")
            return 1
        for name, text in sorted(build().items()):
            (TABLES / name).write_text(render_file(text), encoding="utf-8")
        print(f"gen-domains: wrote {len(build())} declaration file(s)")
        return 0
    if args.check:
        print("gen-domains: declarations are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
