#!/usr/bin/env python3
"""Alias-registry projection: answer sheets -> build/param-aliases.toml.

The law source is the `alias: [...]` face on answer-sheet column rows
(mcode comp books; mcd 3.design/library/305 section 3). This script only
projects it into a flat lookup table for scraping pipelines; the output is
regenerable and never hand-edited. Canonical keys stay the only key face;
aliases never enter spec keys (check-spec-keys enforces the consumer side).
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "build" / "param-aliases.toml"

# Type face runs to the `alias:` comma and may carry arguments or a cond
# group: `Voltage(range)`, `Ratio(cond(ic: Current, vce: Voltage))`.
ROW = re.compile(r'^(\s{4,})(\w+)\s+=\s+(.+?),\s*alias:\s*\[([^\]]*)\]')
RECIPE = re.compile(r'^recipe\s+([\w.]+)')
# Group opener: `name = [` alone on its line (an inline `[B, C, E]` pin row
# closes on the same line and is data, not a group).
GROUP = re.compile(r'^(\s{4,})(\w+)\s+=\s*\[\s*$')
# Group closer: a bare `]` at the opener's indent.
CLOSE = re.compile(r'^(\s{4,})\]\s*$')


def main() -> int:
    rows = []
    for path in sorted((ROOT / "comp").glob("*.mc")):
        recipe = None
        stack = []  # (indent, group name), innermost last
        for line in path.read_text().splitlines():
            m = RECIPE.match(line)
            if m:
                recipe, stack = m.group(1), []
                continue
            m = CLOSE.match(line)
            if m:
                indent = len(m.group(1))
                while stack and stack[-1][0] >= indent:
                    stack.pop()
                continue
            m = GROUP.match(line)
            if m:
                stack.append((len(m.group(1)), m.group(2)))
                continue
            m = ROW.match(line)
            if m and recipe and stack:
                indent, col, typ, aliases = m.groups()
                # the row's group is the innermost opener strictly above it
                group = next((g for i, g in reversed(stack)
                              if i < len(indent)), None)
                if group is None:
                    continue
                names = [a.strip() for a in aliases.split(",") if a.strip()]
                if names:
                    rows.append((recipe, group, col, typ, names, path.name))

    lines = [
        "# Generated by scripts/alias-projection.py - regenerable, never hand-edited.",
        "# Law source: alias: [...] faces on comp/*.mc answer-sheet columns (305 s3).",
        "",
    ]
    for recipe, group, col, typ, names, src in rows:
        lines.append(f'["{recipe}.{col}"]')
        lines.append(f'group = "{group}"')
        lines.append(f'type = "{typ}"')
        lines.append("aliases = [" + ", ".join(f'"{n}"' for n in names) + "]")
        lines.append(f'source = "comp/{src}"')
        lines.append("")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"alias-projection: {len(rows)} columns -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
